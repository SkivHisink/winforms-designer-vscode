/// <summary>
/// The style Visual Studio writes for a modern (.NET 6+) project: no <c>this.</c>, and type names left unqualified
/// because the project's implicit usings import their namespaces (<c>button1 = new Button();</c>,
/// <c>SuspendLayout();</c>). The modern interpreter binds those names through the file's usings, its namespaces and
/// the project's sources, confirms each inferred binding against the project's build, and refuses — with a reason —
/// what either cannot settle the way the compiler did.
/// </summary>
public sealed class SimplifiedDesignerStyleTests
{
