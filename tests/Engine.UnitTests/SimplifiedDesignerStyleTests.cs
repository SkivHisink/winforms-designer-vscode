    [Fact]
    public void AnotherStatementsOperation_DoesNotConfirmThisOne()
    {
        // The first statement really reads System.Drawing.Color.Red; the second, under an alias no project file
        // shows, reads Corporate.Palette.Red (blue). Evidence from the method as a whole would accept both as red.
        const string designer = """
            using System.Drawing;
            namespace WfdTest;
            partial class Form1 {
                private void InitializeComponent() {
                    this.BackColor = System.Drawing.Color.Red;
                    this.ForeColor = Color.Red;
                    this.Location = new System.Drawing.Point(1, 2);
                    this.Size = new Point(300, 200);
                }
            }
            """;
        using var project = new TempProject(PlainProject);
        project.Build(designer, """
            global using Color = Corporate.Palette;
            global using Point = System.Drawing.Size;
            namespace Corporate { public static class Palette { public static System.Drawing.Color Red => System.Drawing.Color.Blue; } }
            """);
        var layout = project.Render(designer);

        Assert.Contains(layout.Unrepresentable, u => u.StartsWith("this.ForeColor = Color.Red;", StringComparison.Ordinal)
            && u.Contains("compiled this statement differently", StringComparison.Ordinal));
        Assert.Contains(layout.Unrepresentable, u => u.StartsWith("this.Size = new Point(300, 200);", StringComparison.Ordinal)
            && u.Contains("compiled this statement differently", StringComparison.Ordinal));
        Assert.DoesNotContain(layout.Unrepresentable, u => u.StartsWith("this.BackColor", StringComparison.Ordinal));
    }

