    private static ClassDeclarationSyntax FormClass(string source) =>
        CSharpSyntaxTree.ParseText(source).GetRoot().DescendantNodes().OfType<ClassDeclarationSyntax>().First();

    /// <summary>A scope over this test assembly plus WinForms and corelib, with the project facts given.</summary>
    private static DesignerTypeScope TestScope(ClassDeclarationSyntax cls, Func<ProjectSourceFacts> project,
        IReadOnlyList<(string Namespace, string Name)>? bufferDeclarations = null,
        IReadOnlyDictionary<string, string?>? designedMembers = null)
    {
        var asm = typeof(SimplifiedDesignerStyleTests).Assembly;
        var search = new[] { asm, typeof(System.Windows.Forms.Control).Assembly, typeof(object).Assembly };
        return new DesignerTypeScope(DesignerIrBuilder.SourceScopesOf(cls), search, asm,
            name => search.Select(a => a.GetType(name)).FirstOrDefault(t => t != null), project,
            designedMembers: designedMembers, bufferDeclarations: bufferDeclarations);
    }

    /// <summary>A throwaway project folder: one .csproj plus the given files, deleted afterwards.</summary>
    private sealed class TempProject : IDisposable
    {
        public string Dir { get; }

        public TempProject(string csproj, params (string Path, string Text)[] files)
        {
            Dir = Path.Combine(Path.GetTempPath(), "wfd-simplified-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(Dir);
            File.WriteAllText(Path.Combine(Dir, "WfdTest.csproj"), csproj);
            File.WriteAllText(Path.Combine(Dir, "Form1.cs"),
                "namespace WfdTest;\npublic partial class Form1 : System.Windows.Forms.Form { }\n");
            foreach (var (relative, text) in files)
            {
                string full = Path.Combine(Dir, relative);
                Directory.CreateDirectory(Path.GetDirectoryName(full)!);
                File.WriteAllText(full, text);
            }
        }

        /// <summary>Compile the project as its build would — every C# file of the folder (nested projects' folders
        /// left out) with <paramref name="designerSource"/> as Form1.Designer.cs — plus <paramref name="unseenSource"/>,
        /// which stands for what a package or a source generator adds without any file in the project showing it.
        /// The assembly goes where the engine's build-output search finds it.</summary>
        public void Build(string designerSource, string? unseenSource = null, bool optimized = false)
        {
            var trees = new List<SyntaxTree> { CSharpSyntaxTree.ParseText(designerSource, path: "Form1.Designer.cs") };
            foreach (string file in Directory.EnumerateFiles(Dir, "*.cs", SearchOption.AllDirectories))
            {
                string? folder = Path.GetDirectoryName(file);
                if (folder != Dir && Directory.EnumerateFiles(folder!, "*.csproj").Any()) continue;
                if (Path.GetFileName(file) == "Form1.Designer.cs") continue;
                trees.Add(CSharpSyntaxTree.ParseText(File.ReadAllText(file), path: file));
            }
            if (unseenSource != null) trees.Add(CSharpSyntaxTree.ParseText(unseenSource, path: "Unseen.g.cs"));
            var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
                .Split(Path.PathSeparator).Select(p => MetadataReference.CreateFromFile(p));
            var compilation = CSharpCompilation.Create("WfdTest", trees, references,
                new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Disable,
                    optimizationLevel: optimized ? OptimizationLevel.Release : OptimizationLevel.Debug));
            string output = Path.Combine(Dir, "bin", "Debug", "net10.0-windows", "WfdTest.dll");
            Directory.CreateDirectory(Path.GetDirectoryName(output)!);
            using var stream = File.Create(output);
            var emitted = compilation.Emit(stream);
            Assert.True(emitted.Success, string.Join(Environment.NewLine,
                emitted.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error)));
        }

        public RenderLayoutResult Render(string designerSource, string relativePath = "Form1.Designer.cs")
        {
            string designer = Path.Combine(Dir, relativePath);
            Directory.CreateDirectory(Path.GetDirectoryName(designer)!);
            File.WriteAllText(designer, designerSource);
            return Sta.Invoke(() => DesignerRenderer.RenderWithLayout(designer, sourceText: designerSource));
        }

        public void Dispose()
        {
            try { Directory.Delete(Dir, recursive: true); } catch { /* best effort */ }
        }
    }
