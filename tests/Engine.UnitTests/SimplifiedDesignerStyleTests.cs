    [Theory]
    [InlineData(false)]
    [InlineData(true)] // an optimized build has no nop between statements
    public void IssueDesigner_RendersAsTheProjectsBuildCompiledIt(bool optimized)
    {
        using var project = new TempProject(ModernProject, (GeneratedPath, GeneratedGlobalUsings));
