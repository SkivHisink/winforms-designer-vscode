import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'docs/v2/designer-protocol-v2.schema.json');
const schemaText = readFileSync(schemaPath, 'utf8');
const schema = JSON.parse(schemaText);
const check = process.argv.includes('--check');

function stable(value) {
  if (Array.isArray(value)) {
    return `[${value.map(stable).join(',')}]`;
  }
  if (value && typeof value === 'object') {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${stable(value[key])}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

const schemaHash = createHash('sha256').update(stable(schema)).digest('hex');
const banner = `// <auto-generated>\n// Generated by scripts/generate-v2-protocol.mjs from docs/v2/designer-protocol-v2.schema.json.\n// Schema SHA-256: ${schemaHash}\n// </auto-generated>\n`;
const caps = schema.capabilities;
const outcomeKinds = schema.outcomes.kinds;
const messageKinds = schema.envelope.messageKinds;
const outcomeCodes = Object.entries(schema.outcomes.codes).flatMap(([, values]) => values);
const outcomeCodeEntries = Object.entries(schema.outcomes.codes);
const envelopeRequiredFields = schema.envelope.requiredFields;
const envelopeOptionalFields = schema.envelope.optionalFields ?? [];
const envelopeAllowedFields = [...envelopeRequiredFields, ...envelopeOptionalFields];
const fingerprintFields = schema.fingerprint.requiredFields;

function tsStringArray(values) {
  return values.map((value) => `  ${JSON.stringify(value)}`).join(',\n');
}

function csStringArray(values) {
  return values.map((value) => `            "${value}"`).join(',\n');
}

function pascal(value) {
  return value.split(/[^a-z0-9]+/i).filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join('');
}

