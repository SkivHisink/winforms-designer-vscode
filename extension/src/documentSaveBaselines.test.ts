import { describe, expect, it } from 'vitest';
import { readDocumentSaveBaselines } from './documentSaveBaselines';

const missing = () => Object.assign(new Error('absent'), { code: 'ENOENT' });
const isMissing = (error: unknown) => (error as { code?: string })?.code === 'ENOENT';
const image = (text: string, hadBom = false) => ({ text, hadBom });

describe('aggregate save baseline reads', () => {
  it('waits for and rejects a missing companion when a new generated file rejects first', async () => {
    let companionReadSettled = false;
    const generated = Promise.reject(missing());
    const companion = Promise.resolve().then(() => {
      companionReadSettled = true;
      throw missing();
    });
    await expect(readDocumentSaveBaselines(generated, [{ read: companion, expectedText: 'handler' }], false, isMissing))
      .rejects.toMatchObject({ code: 'COMPANION_CHANGED' });
    expect(companionReadSettled).toBe(true);
  });

  it('rejects a stale successful companion even when the generated file rejects first', async () => {
    await expect(readDocumentSaveBaselines(Promise.reject(missing()), [{
      read: Promise.resolve().then(() => image('externally changed')), expectedText: 'handler',
    }], false, isMissing)).rejects.toMatchObject({ code: 'COMPANION_CHANGED' });
  });

  it('permits creating a new generated file only after all companions match', async () => {
    await expect(readDocumentSaveBaselines(Promise.reject(missing()), [{
      read: Promise.resolve(image('handler')), expectedText: 'handler',
    }], false, isMissing)).resolves.toBeNull();
  });

  it('refuses a generated file removed after the baseline was established', async () => {
    await expect(readDocumentSaveBaselines(Promise.reject(missing()), [], true, isMissing))
      .rejects.toMatchObject({ code: 'GENERATED_BASELINE_MISSING' });
  });

  it('preserves non-missing generated read failures instead of treating them as a new file', async () => {
    const access = Object.assign(new Error('locked'), { code: 'EACCES' });
    await expect(readDocumentSaveBaselines(Promise.reject(access), [], false, isMissing)).rejects.toBe(access);
  });

  it('returns the exact generated byte metadata after all companion text checks pass', async () => {
    await expect(readDocumentSaveBaselines(Promise.resolve(image('source\r\n', true)), [{
      read: Promise.resolve(image('handler\r\n', true)), expectedText: 'handler\r\n',
    }], true, isMissing)).resolves.toEqual(image('source\r\n', true));
  });
});
